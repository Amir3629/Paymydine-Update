  function translateTextNode(node) {
    if (!node || !node.parentElement) return;
    var parent = node.parentElement;
    if (!parent.closest(allowed) || parent.closest(excluded) ||
        parent.closest('script,style,textarea,option,pre,code')) return;
    var original = node.nodeValue || '';
    var trimmed = original.trim();
    if (!trimmed || !Object.prototype.hasOwnProperty.call(words, trimmed)) return;
    node.nodeValue = original.replace(trimmed, words[trimmed]);
  }

  function translate(element) {
    if (!element) return;
    var walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
    var node;
    while ((node = walker.nextNode())) translateTextNode(node);
    element.querySelectorAll('input,textarea,button,a').forEach(function (control) {
      if (!control.closest(allowed) || control.closest(excluded)) return;
      ['placeholder','aria-label','title'].forEach(function (attribute) {
        var value = control.getAttribute(attribute);
        if (value && Object.prototype.hasOwnProperty.call(words, value)) {
          control.setAttribute(attribute, words[value]);
        }
      });
    });
  }

