  window.PMD_STAFF_TRANSLATE = function (value) {
    var source = String(value == null ? '' : value);
    return words && Object.prototype.hasOwnProperty.call(words, source) ? words[source] : source;
  };
  if (!words) return;

  var excluded = '.pmd-staff-chat__messages,.pmd-staff-request-history,.pmd-staff-month-shifts,' +
    '.pmd-staff-management-list,.pmd-staff-profile-readonly,.pmd-staff-mobile-groups,' +
    '.pmd-staff-selected-shift,.pmd-staff-open-shifts,[data-pmd-employee-content]';
